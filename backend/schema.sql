CREATE TABLE IF NOT EXISTS users (
  user_id INT PRIMARY KEY AUTO_INCREMENT, full_name VARCHAR(160) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL,
  phone VARCHAR(32), role VARCHAR(32) NOT NULL DEFAULT 'jobseeker'
);
CREATE TABLE IF NOT EXISTS company (
  company_id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(160) NOT NULL,
  industry VARCHAR(120), size VARCHAR(80), website VARCHAR(500), description TEXT,
  location VARCHAR(180), email VARCHAR(254) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS jobs (
  job_id INT PRIMARY KEY AUTO_INCREMENT, company_id INT NOT NULL, title VARCHAR(200) NOT NULL,
  description TEXT NOT NULL, requirements TEXT, location VARCHAR(180) NOT NULL,
  salary_min DECIMAL(14,2), salary_max DECIMAL(14,2), job_type VARCHAR(60),
  posted_date DATE NOT NULL, expiry_date DATE NOT NULL,
  FOREIGN KEY (company_id) REFERENCES company(company_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS applications (
  application_id INT PRIMARY KEY AUTO_INCREMENT, job_id INT NOT NULL, user_id INT NOT NULL,
  application_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP, status VARCHAR(32) NOT NULL DEFAULT 'Applied',
  UNIQUE (job_id,user_id), FOREIGN KEY (job_id) REFERENCES jobs(job_id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS password_resets (
  user_id INT PRIMARY KEY, code_hash CHAR(64) NOT NULL, attempts INT NOT NULL DEFAULT 0,
  token_hash CHAR(64), expires_at DATETIME NOT NULL, sent_at DATETIME NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);
